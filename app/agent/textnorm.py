# -*- coding: utf-8 -*-
"""تطبيع النص العربي/العراقي قبل أي مطابقة.

المستخدم يكتب نفس الكلمة بأشكال كثيرة: "أحمد" / "احمد" / "أحمدْ"، "الكهرباء" /
"الكهربه"، "گ" بدل "ك"، أرقام هندية "٥٠" بدل "50". كل المطابقات بالمشروع
(أسماء، مبالغ، كلمات النية) تمر من هنا أولاً حتى تكون المقارنة على شكل موحّد.
"""

import re

# الشرح: جداول التحويل.
#   - _DIACRITICS: التشكيل (فتحة، ضمة، شدة...) + التطويل "ـ" — ما يغيّر المعنى فنحذفه.
#   - _CHAR_MAP: توحيد الحروف المتشابهة (همزات، ى/ي، ة/ه) والحروف العراقية
#     (گ چ پ ڤ) لأقرب حرف عربي قياسي.
#   - _DIGITS: الأرقام الهندية (٠-٩) والفارسية (۰-۹) → أرقام لاتينية.
_DIACRITICS = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭـ]")
_CHAR_MAP = str.maketrans({
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا",
    "ى": "ي", "ئ": "ي", "ؤ": "و", "ة": "ه",
    "گ": "ك", "ڭ": "ك", "چ": "ج", "پ": "ب", "ڤ": "ف", "ژ": "ز",
    "،": ",", "٬": ",", "٫": ".", "؟": "?", "؛": ";",
})
_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")


def normalize(text: str) -> str:
    """يرجّع نسخة موحّدة من النص: بلا تشكيل، حروف موحّدة، أرقام لاتينية،
    ومسافات مفردة. ما يغيّر ترتيب الكلمات ولا يحذف كلمات."""
    text = _DIACRITICS.sub("", text or "")
    # حرف الجر "على" (بالألف المقصورة) يصير "علي" بعد توحيد ى→ي، ويتطابق غلط
    # مع اسم "علي". نحوّله لـ "الى" قبل التوحيد. ("علي" المكتوبة بالياء تبقى اسماً.)
    text = re.sub(r"(?<![\w])على(?![\w])", "الى", text)
    text = text.translate(_CHAR_MAP).translate(_DIGITS)
    return re.sub(r"\s+", " ", text).strip().lower()


# الشرح: السوابق الملتصقة بالكلمة بالعربي: "لأحمد" = ل + أحمد، "للمحل" = لل + محل،
# "والكهرباء" = و + ال + كهرباء. نولّد كل الأشكال الممكنة للكلمة بعد نزع
# السوابق حتى "لاحمد" يطابق جهة اتصال اسمها "احمد".
_PREFIXES = ("وال", "بال", "لل", "ال", "و", "ل", "ب")


def token_variants(token: str) -> set:
    """كل الأشكال الممكنة للكلمة بعد نزع سابقة واحدة أو اثنتين (و + ل ...)."""
    variants = {token}
    for _ in range(2):
        for v in list(variants):
            for p in _PREFIXES:
                if v.startswith(p) and len(v) - len(p) >= 2:
                    variants.add(v[len(p):])
    return variants


def tokens(text: str) -> list:
    """يقسّم النص المطبَّع لكلمات:
      - يفصل الأرقام الملتصقة بالحروف: "50الف" → "50 الف".
      - يحذف علامات الترقيم الملتصقة: "لزينب." → "لزينب".
      - يحافظ على إشارة السالب: "-5000" (حتى نرفضه بدل ما نقرأه 5000).
      - يجمع رقم الهاتف المكتوب بمسافات/شرطات: "0770-123-4567" → "07701234567"."""
    text = re.sub(r"(?<!\d)(0\s*7(?:[\s-]*\d){9})(?!\d)", lambda m: re.sub(r"[\s-]", "", m.group(1)), text)
    text = re.sub(r"(\d)([^\d\s.,])", r"\1 \2", text)
    text = re.sub(r"([^\d\s.,-])(\d)", r"\1 \2", text)
    return re.findall(r"(?<![\d\w])-\d+(?:[.,]\d+)*|\d+(?:[.,]\d+)*|[^\W\d_]+", text)


def similarity(a: str, b: str) -> float:
    """تشابه بين كلمتين من 0 إلى 1 (مبني على مسافة التحرير Levenshtein).
    نستعمله لاكتشاف الأسماء المتشابهة (زينب/زينه) حتى **نسأل** بدل ما نخمّن."""
    if a == b:
        return 1.0
    if not a or not b:
        return 0.0
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return 1.0 - prev[-1] / max(len(a), len(b))
